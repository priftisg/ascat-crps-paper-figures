import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = research_root(Path(__file__))
ensure_sys_path(ROOT)

SATELLITE_LABELS = {
    "ascat_a": "ASCAT-A",
    "ascat_b": "ASCAT-B",
    "ascat_c": "ASCAT-C",
}
SATELLITE_COLORS = {
    "ascat_a": "#1f77b4",
    "ascat_b": "#ff7f0e",
    "ascat_c": "#2ca02c",
}
PAIRS = [
    ("ascat_a", "ascat_b", "A–B"),
    ("ascat_a", "ascat_c", "A–C"),
    ("ascat_b", "ascat_c", "B–C"),
]


def pairwise_corr(monthly: pd.DataFrame, metric: str) -> dict:
    wide = monthly.pivot_table(index="month", columns="satellite", values=metric)
    out = {}
    for a, b, lab in PAIRS:
        if a not in wide.columns or b not in wide.columns:
            out[lab] = np.nan
            continue
        sub = wide[[a, b]].dropna()
        if len(sub) < 3:
            out[lab] = np.nan
        else:
            out[lab] = float(sub[a].corr(sub[b]))
    return out


def plot_monthly_timeseries(monthly: pd.DataFrame, out_path: Path, title: str) -> None:
    metrics = [
        ("objects_per_swath", "Objects per swath", "(a)"),
        ("coldpool_pixels_per_swath", "Cold-pool pixels per swath", "(b)"),
        ("mean_object_area_km2", r"Mean object area (km$^2$)", "(c)"),
    ]
    fig, axes = plt.subplots(3, 1, figsize=(10, 9), sharex=True)
    months_sorted = sorted(monthly["month"].unique())

    for ax, (col, ylab, panel) in zip(axes, metrics):
        for satellite, sub in monthly.groupby("satellite"):
            sub = sub.set_index("month").reindex(months_sorted)
            ax.plot(
                months_sorted,
                sub[col],
                "o-",
                lw=1.8,
                ms=4,
                label=SATELLITE_LABELS.get(satellite, satellite),
                color=SATELLITE_COLORS.get(satellite),
            )
        ax.set_ylabel(ylab)
        ax.grid(True, alpha=0.3)
        ax.legend(loc="best", fontsize=9)
        ax.text(0.01, 0.97, panel, transform=ax.transAxes, fontsize=12, va="top")

    axes[-1].set_xlabel("Month")
    n_ticks = len(months_sorted)
    step = max(1, n_ticks // 12)
    axes[-1].set_xticks(months_sorted[::step])
    axes[-1].tick_params(axis="x", rotation=45)
    if title:
        fig.suptitle(title, fontsize=13)
    fig.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=220, bbox_inches="tight", facecolor="white")
    fig.savefig(out_path.with_suffix(".pdf"), bbox_inches="tight", facecolor="white")
    plt.close(fig)


def write_correlation_table(monthly: pd.DataFrame, out_dir: Path) -> pd.DataFrame:
    metrics = [
        ("objects_per_swath", "Objects per swath"),
        ("coldpool_pixels_per_swath", "Cold-pool pixels per swath"),
        ("mean_object_area_km2", "Mean object area"),
    ]
    rows = []
    for col, name in metrics:
        c = pairwise_corr(monthly, col)
        rows.append({"Metric": name, **c})
    corr = pd.DataFrame(rows)
    corr.to_csv(out_dir / "correlation_table.csv", index=False)

    def fmt(x):
        return "—" if pd.isna(x) else f"{x:.2f}"

    lines = [
        "% Auto-generated by plot_crps_cross_platform.py",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\caption{Pairwise Pearson correlation coefficients for monthly "
        r"cross-platform CRPS density-matched catalog statistics "
        r"($\tau=1.2\times10^{-4}$, $p^*=0.325$; 2019--2021 overlap). "
        r"Objects per swath $=N_{\mathrm{obj}}/N_{\mathrm{swath}}$; "
        r"cold-pool pixels per swath $=\sum n_{\mathrm{pixels}}/N_{\mathrm{swath}}$; "
        r"mean object area is the monthly mean of object $area\_km2$ "
        r"(tropical objects, $|\phi|\le 30^\circ$).}",
        r"\label{tab:cross_platform_correlation_crps}",
        r"\begin{tabular}{lccc}",
        r"\hline",
        r"Metric & A--B & A--C & B--C \\",
        r"\hline",
    ]
    for _, r in corr.iterrows():
        lines.append(
            f"{r['Metric']} & {fmt(r['A–B'])} & {fmt(r['A–C'])} & {fmt(r['B–C'])} \\\\"
        )
    lines += [r"\hline", r"\end{tabular}", r"\end{table}", ""]
    (out_dir / "correlation_table.tex").write_text("\n".join(lines))
    return corr


def write_paper_snippet(out_dir: Path, corr: pd.DataFrame) -> None:
    def g(metric, pair):
        row = corr.loc[corr["Metric"] == metric, pair]
        if len(row) == 0 or pd.isna(row.iloc[0]):
            return "—"
        return f"{row.iloc[0]:.2f}"

    text = (
        r"""\subsubsection{Cross-Platform Consistency During Overlapping Years}

Periods when multiple ASCAT satellites were simultaneously operational provide an
opportunity to evaluate the consistency of the cold-pool dataset across independent
observing platforms. This analysis focuses on the 2019--2021 period, during which
ASCAT-A, ASCAT-B, and ASCAT-C were simultaneously available (ASCAT-C from mid-2019).

For each satellite, monthly catalog statistics are computed from the density-matched
CRPS probabilistic object catalog ($\tau=1.2\times10^{-4}$, $p^*=0.325$) using
identical post-processing. The three metrics are: (i)~objects per swath
($N_{\mathrm{obj}}/N_{\mathrm{swath}}$), (ii)~cold-pool pixels per swath
($\sum n_{\mathrm{pixels}}/N_{\mathrm{swath}}$), and (iii)~mean object area.
Pairwise Pearson correlations of the monthly series are high for objects per swath
(A--B $= """
        + g("Objects per swath", "A–B")
        + r""", A--C $= """
        + g("Objects per swath", "A–C")
        + r""", B--C $= """
        + g("Objects per swath", "B–C")
        + r""") and cold-pool pixels per swath
(A--B $= """
        + g("Cold-pool pixels per swath", "A–B")
        + r""", A--C $= """
        + g("Cold-pool pixels per swath", "A–C")
        + r""", B--C $= """
        + g("Cold-pool pixels per swath", "B–C")
        + r"""), with somewhat lower but still
positive agreement for mean object area
(A--B $= """
        + g("Mean object area", "A–B")
        + r""", A--C $= """
        + g("Mean object area", "A–C")
        + r""", B--C $= """
        + g("Mean object area", "B–C")
        + r"""). These results indicate that the probabilistic
multi-platform catalog is sufficiently homogeneous for climatological analyses over
the MetOp-A/B/C overlap era.

"""
    )
    (out_dir / "paper_snippet.tex").write_text(text)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--stats",
        default=str(
            ROOT / "evaluation/cross_platform/crps/triple_overlap/monthly_stats.csv"
        ),
    )
    p.add_argument(
        "--outdir",
        default=str(
            ROOT
            / "evaluation/cross_platform/crps/triple_overlap/figures"
        ),
    )
    p.add_argument(
        "--pack-dir",
        default=str(
            ROOT
            / "figures/main"
        ),
    )
    args = p.parse_args()

    stats_path = Path(args.stats)
    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)

    monthly = pd.read_csv(stats_path)
    if "gpkg_ok" in monthly.columns:
        monthly = monthly[monthly["gpkg_ok"]].copy()
    elif "gpkg_exists" in monthly.columns:
        monthly = monthly[monthly["gpkg_exists"]].copy()

    fig1 = outdir / "fig1_monthly_timeseries.png"
    plot_monthly_timeseries(monthly, fig1, title="")
    print("wrote", fig1)
    print("wrote", fig1.with_suffix(".pdf"))

    corr = write_correlation_table(monthly, outdir)
    write_paper_snippet(outdir, corr)
    print("wrote", outdir / "correlation_table.csv")
    print("wrote", outdir / "paper_snippet.tex")
    print(corr.to_string(index=False))

    pack = Path(args.pack_dir)
    pack.mkdir(parents=True, exist_ok=True)
    for src_name, dst_name in [
        ("fig1_monthly_timeseries.png", "11_cross_platform_monthly_timeseries.png"),
        ("fig1_monthly_timeseries.pdf", "11_cross_platform_monthly_timeseries.pdf"),
        ("correlation_table.csv", "11_cross_platform_correlation.csv"),
        ("correlation_table.tex", "11_cross_platform_correlation.tex"),
        ("paper_snippet.tex", "11_cross_platform_paper_snippet.tex"),
    ]:
        src = outdir / src_name
        if src.exists():
            dst = pack / dst_name
            dst.write_bytes(src.read_bytes())
            print("copied", dst)


if __name__ == "__main__":
    main()
